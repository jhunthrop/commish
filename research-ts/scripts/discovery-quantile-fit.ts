// Fits the discovery candidate generator's quantile thresholds on TRAIN predictor seasons only and
// generates the committed `src/projections/laws/discovery/quantiles.ts`.
// Run: npm run laws:discover:quantiles
//
// Mirrors `preseason-fit.ts`'s own committed-constant pattern: the candidate generator
// (`discovery/generate.ts`) is a PURE function of this table, so "what did discovery believe a
// quantity's quantiles were" (the low band and the high one both, since Task 2 of the
// discovery-expansion plan) has to be answerable from the repository alone, with no
// database and no network at generation time. Fitted on
// `DISCOVERY_TRAIN_SEASONS` (`laws/config.ts`) and nothing later — `computeQuantileTable` itself
// re-enforces that gate rather than trusting this script to have filtered correctly.
import { writeFileSync } from "node:fs";
import { createDb } from "@research-ts/db/client";
import { allPositions } from "@research-ts/projections/backtest";
import { PPR_SCORING } from "@research-ts/domain/scoring";
import { DISCOVERY_TRAIN_SEASONS } from "@research-ts/projections/laws/config";
import { discoveryFactsForSeason } from "@research-ts/projections/laws/discovery-facts";
import {
  computeQuantileTable,
  QUANTILE_LEVELS,
  QUANTILE_TAG,
  QUANTITY_DEFS,
  type QuantityRow,
} from "@research-ts/projections/laws/discovery/templates";
import { preseasonMomentFor } from "@research-ts/projections/preseason/source";
import { packagePath } from "@research-ts/lib/package-path";

const OUTPUT = packagePath("src/projections/laws/discovery/quantiles.ts");

function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") {
    throw new Error(`${name} is not set. Run this through \`npm run laws:discover:quantiles\`, which loads .env.local.`);
  }
  return value;
}

function header(): string {
  return `import type { QuantileTable } from "./templates";

/**
 * GENERATED by \`npm run laws:discover:quantiles\`. Do not edit by hand.
 *
 * Committed rather than computed at generation time, for the reason \`preseason/fitted.ts\` and
 * \`model/fitted.ts\` are: what the discovery candidate generator believed a quantity's train-window
 * quantile was has to be answerable from the repository alone. Fitted on predictor seasons
 * ${DISCOVERY_TRAIN_SEASONS.from}-${DISCOVERY_TRAIN_SEASONS.to} and on nothing later
 * (\`DISCOVERY_TRAIN_SEASONS\`, \`laws/config.ts\`) — see \`discovery-quantile-fit.ts\`.
 */
`;
}

async function main(): Promise<void> {
  const db = createDb(requireEnv("DATABASE_URL"));
  const positions = await allPositions(db);

  const rows: QuantityRow[] = [];
  for (let season = DISCOVERY_TRAIN_SEASONS.from; season <= DISCOVERY_TRAIN_SEASONS.to; season++) {
    // `admitDerived: true` — the laws harness (discovery included) is exactly where a pbp-derived
    // gap-season stat line belongs, the same choice `buildPopulations` makes for the tribal laws.
    // The same `incomingAsOf` `scripts/discover-laws.ts` passes, for the same reason: a quantile
    // fitted at a gate the quantity is invisible at would be fitted on nothing at all.
    const incomingAsOf = await preseasonMomentFor(db, season + 1);
    const facts = await discoveryFactsForSeason(db, season, positions, PPR_SCORING, true, incomingAsOf);
    for (const { position, current } of facts.values()) {
      rows.push({ season, position, values: current });
    }
  }

  const table = computeQuantileTable(rows, { to: DISCOVERY_TRAIN_SEASONS.to });

  console.log(`DISCOVERY QUANTILES, fitted on ${rows.length} player-seasons across ${DISCOVERY_TRAIN_SEASONS.from}-${DISCOVERY_TRAIN_SEASONS.to}\n`);
  for (const def of QUANTITY_DEFS) {
    for (const position of def.positions) {
      const thresholds = table[def.id]?.[position];
      if (thresholds === undefined) {
        console.log(`  ${def.id.padEnd(40)} ${position}  (too few train-season observations)`);
        continue;
      }
      // Every level in `QUANTILE_LEVELS`, read off the list rather than named one by one: the low
      // band joined that list in Task 2 of the discovery-expansion plan, and a hand-listed q70/q80/q90
      // print would have kept reporting three of six thresholds while writing all six to the file.
      const printed = QUANTILE_LEVELS.map((level) => {
        const value = thresholds[level];
        return `${QUANTILE_TAG[level]}=${value === undefined ? "n/a" : value.toFixed(3)}`;
      }).join("  ");
      console.log(`  ${def.id.padEnd(40)} ${position}  ${printed}`);
    }
  }

  writeFileSync(OUTPUT, `${header()}\nexport const DISCOVERY_QUANTILES: QuantileTable = ${JSON.stringify(table, null, 2)};\n`);
  console.log(`\nwrote ${OUTPUT}`);

  await db.$client.end();
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
