import type { StatLine } from "@/domain/player";
import type { ProjectionInput, ProjectionSource } from "../backtest";
import { composeStatLine } from "./compose";
import { applyNewsToOpportunity, contextualiseOpportunity, contextualiseRates, redistributeOpportunity, type ContextPriors } from "./context";
import { predictRates, type EfficiencyPriors } from "./efficiency";
import { SHIPPED_FEATURES, type FeatureFlags } from "./features";
import { FITTED_EFFICIENCY_PRIORS, FITTED_LINE_PRIORS, FITTED_OPPORTUNITY_PRIORS, FITTED_GAME_CONTEXT_PRIORS, FITTED_REDISTRIBUTION_PRIORS, FITTED_NEWS_PRIORS, FITTED_RED_ZONE_PRIORS, FITTED_SCHEME_PRIORS, FITTED_TARGET_DEPTH_PRIORS } from "./fitted";
import { predictOpportunity, type OpportunityPriors } from "./opportunity";

/**
 * THE MODEL, AS THE HARNESS SEES IT — three layers behind one `ProjectionSource`.
 *
 * Layer 1 predicts shares, layer 2 predicts regressed rates, layer 3 multiplies them into a
 * `StatLine`, and `replay` turns that into points through the league's own scoring. Nothing in this
 * file decides anything: it is the seam that lets the model be scored by exactly the same
 * instrument, on exactly the same players, as the naive floor. A source that scored itself would be
 * a source nobody could compare.
 *
 * Both layers are given the SAME `history`, `usage` and `week` — the ones `replay` read through the
 * as-of gate — so the leakage guarantee is the store's, not this file's, and there is no second
 * path for the future to arrive on.
 *
 * A player is projected when both layers have an opinion about him. Layer 1 needs a position and
 * some history; layer 2 needs at least one week where an outcome and an opportunity row line up.
 * Anyone missing gets NO projection rather than a projection of zero — the same discipline the
 * naive benchmark applies to rookies, because emitting zeros dresses ignorance up as a confident
 * wrong opinion and gets it scored as one.
 */

export const MODEL_SOURCE_NAME = "commish-model";

export interface ModelPriors {
  readonly opportunity: OpportunityPriors;
  readonly efficiency: EfficiencyPriors;
  /** Phase 3's fitted context parameters. Read only by groups whose flag is on. */
  readonly context: ContextPriors;
}

/** The committed fit — what the engine actually believes, generated by `npm run projections:fit`. */
export const FITTED_MODEL: ModelPriors = {
  opportunity: FITTED_OPPORTUNITY_PRIORS,
  efficiency: FITTED_EFFICIENCY_PRIORS,
  context: {
    line: FITTED_LINE_PRIORS,
    scheme: FITTED_SCHEME_PRIORS,
    redistribution: FITTED_REDISTRIBUTION_PRIORS,
    gameContext: FITTED_GAME_CONTEXT_PRIORS,
    redZone: FITTED_RED_ZONE_PRIORS,
    targetDepth: FITTED_TARGET_DEPTH_PRIORS,
    news: FITTED_NEWS_PRIORS,
  },
};

export function modelProjection(
  input: ProjectionInput,
  priors: ModelPriors = FITTED_MODEL,
  features: FeatureFlags = SHIPPED_FEATURES,
): readonly StatLine[] {
  const { season, week, history, usage, positions } = input;
  // Scheme sizes the pie, then redistribution decides who eats it. The other order would apply a
  // redistribution to a volume it was never measured against.
  // Scheme sizes the pie, redistribution decides who eats it, and the news pass removes the men who
  // are not at the table. Any other order would apply one of the three to a quantity it was never
  // measured against.
  const opportunity = applyNewsToOpportunity(
    redistributeOpportunity(
      contextualiseOpportunity(
        predictOpportunity(usage, { season, week, positions }, priors.opportunity),
        input,
        features,
        priors.context,
      ),
      input,
      features,
      priors.context,
    ),
    input,
    features,
    priors.context,
  );
  const rates = contextualiseRates(
    predictRates(history, usage, { season, week, positions, firstRosterSeason: input.firstRosterSeason }, priors.efficiency),
    input,
    features,
    priors.context,
  );

  const lines: StatLine[] = [];
  // Iterated in the opportunity map's own order, which `predictOpportunity` sorts by player id: a
  // source whose output order depended on a database read would make a `ScoreCard` subtly
  // irreproducible, and rank correlation is sensitive to tie ordering.
  for (const [playerId, player] of opportunity) {
    const playerRates = rates.get(playerId);
    if (playerRates === undefined) continue;
    lines.push(composeStatLine(playerId, week, player, playerRates));
  }
  return lines;
}

/**
 * The model as a scored source.
 *
 * `name` is a parameter because an ablation runs two arms of the SAME model in one head-to-head,
 * and `replayHeadToHead` reports by name — two sources called the same thing would produce a
 * scoreboard nobody could read.
 */
export function modelSource(
  priors: ModelPriors = FITTED_MODEL,
  features: FeatureFlags = SHIPPED_FEATURES,
  name: string = MODEL_SOURCE_NAME,
): ProjectionSource {
  return { name, project: (input) => modelProjection(input, priors, features) };
}
