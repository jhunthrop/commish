// Fits the per-game performance variance table and generates the committed
// `src/projections/preseason/game-variance-fitted.ts`.
// Run: npm run projections:game-variance:fit
//
// FIT ON 2023-2024, PER THIS CALIBRATION ROUND'S OWN REGISTER DISCIPLINE — 2025 scores (Task 5's
// backtest), 2026 is never touched. A different window from the rest of the preseason model's
// `FIT_SEASONS` (2021, 2022), for the same reason `fit.ts`'s rookie durability prior gets one: this
// table is new work from this calibration round, not a re-fit of something nobody found wrong.
import { writeFileSync } from "node:fs";
import { createDb } from "@/db/client";
import {
  fitGameVariance,
  loadGameVarianceObservations,
  VARIANCE_POSITIONS,
  type GameVariancePriors,
} from "@/projections/preseason/game-variance";

const OUTPUT = "src/projections/preseason/game-variance-fitted.ts";
const TRAIN_SEASONS = [2023, 2024];
const HELD_OUT_SEASONS = [2025, 2026];

function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") {
    throw new Error(`${name} is not set. Run this through \`npm run projections:game-variance:fit\`, which loads .env.local.`);
  }
  return value;
}

function header(): string {
  return `import type { GameVariancePriors } from "./game-variance";

/**
 * GENERATED by \`npm run projections:game-variance:fit\`. Do not edit by hand.
 *
 * Fit on ${TRAIN_SEASONS.join(" and ")} and on nothing else (calibration fix round, 2026-09-04,
 * Task 4). ${HELD_OUT_SEASONS.join(" and ")} are held out — 2025 scores this table's own band
 * calibration in \`docs/research/2026-09-04-rookie-calibration-backtest.md\`, 2026 is never touched.
 */
`;
}

function render(priors: GameVariancePriors): string {
  return `${header()}
export const FITTED_GAME_VARIANCE: GameVariancePriors = ${JSON.stringify(priors, null, 2)};
`;
}

async function main(): Promise<void> {
  const db = createDb(requireEnv("DATABASE_URL"));
  const observations = await loadGameVarianceObservations(db, TRAIN_SEASONS);
  const priors = fitGameVariance(observations, { heldOutSeasons: HELD_OUT_SEASONS });
  await db.$client.end();

  console.log(`PER-GAME VARIANCE, fit on ${observations.length} player-seasons across ${TRAIN_SEASONS.join(", ")}`);
  for (const playerClass of ["rookie", "veteran"] as const) {
    console.log(`\n  ${playerClass}`);
    for (const position of VARIANCE_POSITIONS) {
      const n = observations.filter((o) => o.playerClass === playerClass && o.position === position && o.weeklyPoints.length >= 2).length;
      console.log(`    ${position.padEnd(4)} variance ${priors[playerClass][position].toFixed(2)} (sd ${Math.sqrt(priors[playerClass][position]).toFixed(2)}, n=${n} player-seasons)`);
    }
  }

  writeFileSync(OUTPUT, render(priors));
  console.log(`\nwrote ${OUTPUT}`);
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
