// Fits the rookie curve's own historical games-played rate and generates the committed
// `src/projections/preseason/rookie-historical-games-fitted.ts`.
// Run: npm run projections:rookie-historical-games:fit
//
// SEPARATE FROM `rookie-curve-fit.ts` DELIBERATELY (calibration fix round, 2026-09-04, Task 2), even
// though both read `loadRookieCurveObservations` over the identical `rookieCurveTrainSeasons()`
// window. `rookie-curve-fit.ts`'s own render/check pipeline is pinned by
// `rookie-curve-fit.test.ts` against the EXACT rendered contents of `rookie-curve-fitted.ts`;
// folding a second table into that same generated file would mean either widening those pins for a
// concern they were never written to cover, or risking a silent mismatch between what the test
// checks and what the file holds. A second small file, fit by its own small script, costs nothing
// and touches nothing that fit-round already trusted.
import { writeFileSync } from "node:fs";
import { createDb } from "@/db/client";
import {
  fitHistoricalRookieGamesRate,
  fitRookieCurveEvidence,
  loadRookieCurveObservations,
  ROOKIE_CURVE_TRAIN_CUTOFF_SEASON,
  type HistoricalRookieGamesRate,
  type RookieCurveEvidence,
} from "@/projections/preseason/rookie-curve";
import { HISTORICAL_ROSTER_FLOOR } from "@/projections/nflverse/rosters";
import { rookieCurveTrainSeasons } from "./rookie-curve-fit";

const OUTPUT = "src/projections/preseason/rookie-historical-games-fitted.ts";
const POSITIONS = ["QB", "RB", "WR", "TE"] as const;

function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") {
    throw new Error(`${name} is not set. Run this through \`npm run projections:rookie-historical-games:fit\`, which loads .env.local.`);
  }
  return value;
}

function header(): string {
  return `import type { HistoricalRookieGamesRate, RookieCurveEvidence } from "./rookie-curve";

/**
 * GENERATED by \`npm run projections:rookie-historical-games:fit\`. Do not edit by hand.
 *
 * Fit on rookie classes ${HISTORICAL_ROSTER_FLOOR}-${ROOKIE_CURVE_TRAIN_CUTOFF_SEASON} inclusive —
 * the IDENTICAL population and season window \`rookie-curve-fitted.ts\`'s own points curve is fit
 * against (\`rookieCurveTrainSeasons()\`) — and on nothing else. See \`rookie-curve.ts\`'s
 * \`fitHistoricalRookieGamesRate\` and \`fitRookieCurveEvidence\` docblocks for why the points curve
 * needs a matching games-played rate and evidence count at all.
 */
`;
}

function render(rate: HistoricalRookieGamesRate, evidence: RookieCurveEvidence): string {
  return `${header()}
export const FITTED_HISTORICAL_ROOKIE_GAMES_RATE: HistoricalRookieGamesRate = ${JSON.stringify(rate, null, 2)};

export const FITTED_ROOKIE_CURVE_EVIDENCE: RookieCurveEvidence = ${JSON.stringify(evidence, null, 2)};
`;
}

async function main(): Promise<void> {
  const db = createDb(requireEnv("DATABASE_URL"));
  const seasons = rookieCurveTrainSeasons();
  const observations = await loadRookieCurveObservations(db, seasons);
  const rate = fitHistoricalRookieGamesRate(observations, { heldOutSeasons: [] });
  const evidence = fitRookieCurveEvidence(observations, { heldOutSeasons: [] });
  await db.$client.end();

  console.log(`ROOKIE HISTORICAL GAMES RATE, fit on ${observations.length} rookie-season observations across seasons ${seasons.join(", ")}`);
  for (const position of POSITIONS) {
    const n = observations.filter((o) => o.position === position).length;
    console.log(`  ${position.padEnd(4)} rate ${rate.byPosition[position].toFixed(4)} (n=${n} rookie-seasons)`);
  }

  writeFileSync(OUTPUT, render(rate, evidence));
  console.log(`\nwrote ${OUTPUT}`);
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
