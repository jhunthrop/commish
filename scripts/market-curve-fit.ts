// Fits the ADP-to-points market curve against the store's own historical ADP boards and season
// outcomes, generating the committed `src/projections/market/curve-fitted.ts` (PPR) or, with
// `--format=half` / `--format=std`, `curve-fitted-half.ts` / `curve-fitted-std.ts` (the
// scoring-formats round, 2026-09-08: each format's own feed, scored under its own preset).
// Run: npm run projections:market:fit [-- --format=half|std]
//      npm run projections:market:fit -- --check   (recomputes, exits 1 on any drift)
//
// A FORMAT'S TRAIN WINDOW IS THE SEASONS THE STORE ACTUALLY HOLDS ITS BOARD FOR, inside the same
// structural cutoff. Half PPR is published from 2018, so its fit pools 2018-2021 and the header
// says so; a season with zero rows is reported and contributes nothing rather than being assumed.
//
// TRAIN SEASONS: `BENCHMARK_BOARD_FLOOR` (2013) through `MARKET_CURVE_TRAIN_CUTOFF_SEASON` (2021),
// inclusive. The lower bound is the earliest season this store holds an `ffc_adp_ppr_12` board for,
// and the upper bound is this task's own boundary, enforced structurally inside `fitMarketCurve`
// itself so a mistake here fails loudly rather than quietly leaking a later season into the fit.
//
// THIS WINDOW NO LONGER FOLLOWS `HISTORICAL_ROSTER_FLOOR` (fit-round Task 1). It used to read that
// constant, which was correct only while the two numbers happened to be equal. The roster floor moved
// to 2003 in that round; the ADP boards did not appear before 2013 and could not. A train window
// anchored to the roster floor would now pool ten seasons with no market price in them at all and
// report the same curve as though it had a decade more evidence.
//
// UNLIKE `rookie-curve-fit.ts`, this script does NOT ingest anything itself. The ADP boards it reads
// (`ffc_adp_ppr_12`, via `preseason/store.ts`) are per-season, network-fetched and resolution-checked
// by `preseason-ingest.ts` (a 70% resolution bar, reported per season) — replaying that ingestion
// logic here would be a second, divergent copy of it. Run `npm run projections:preseason:ingest` for
// the train seasons first; this script reads the store only and reports, per season, how many ADP
// rows it found, so a season silently missing its board is visible rather than assumed.
import { readFileSync, writeFileSync } from "node:fs";
import { createDb } from "@research/db/client";
import { BENCHMARK_BOARD_FLOOR } from "@research/projections/preseason/benchmarks";
import { BOARD_FORMAT_SPECS, DEFAULT_BOARD_FORMAT, isBoardFormat, type BoardFormat } from "@research/projections/preseason/board-formats";
import { preseasonRankingsAsOf } from "@research/projections/preseason/store";
import { fitMarketCurve, loadMarketCurveObservations, marketCurve, MARKET_CURVE_TRAIN_CUTOFF_SEASON, type MarketCurvePriors } from "@research/projections/market/curve";

/** Where each format's fit lands, and the constant it exports. PPR keeps the file and the name every
 *  reader already imports; the two new formats get their own files rather than growing a 2,000-line
 *  one further. */
const OUTPUTS: Readonly<Record<BoardFormat, { readonly path: string; readonly constant: string }>> = {
  ppr: { path: "research/src/projections/market/curve-fitted.ts", constant: "FITTED_MARKET_CURVE" },
  half: { path: "research/src/projections/market/curve-fitted-half.ts", constant: "FITTED_MARKET_CURVE_HALF" },
  std: { path: "research/src/projections/market/curve-fitted-std.ts", constant: "FITTED_MARKET_CURVE_STD" },
};
const POSITIONS = ["QB", "RB", "WR", "TE"] as const;
const SANITY_RANKS = [1, 12, 50, 150] as const;

/** Far past any correction: a fit measures completed seasons, never a point-in-time product read. */
const FINAL_OUTCOME = new Date("9999-12-31T00:00:00.000Z");

function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") {
    throw new Error(`${name} is not set. Run this through \`npm run projections:market:fit\`, which loads .env.local.`);
  }
  return value;
}

function trainSeasons(): readonly number[] {
  const seasons: number[] = [];
  for (let season = BENCHMARK_BOARD_FLOOR; season <= MARKET_CURVE_TRAIN_CUTOFF_SEASON; season += 1) seasons.push(season);
  return seasons;
}

function parseFormat(argv: readonly string[]): BoardFormat {
  const flag = argv.find((argument) => argument.startsWith("--format="));
  if (flag === undefined) return DEFAULT_BOARD_FORMAT;
  const value = flag.slice("--format=".length);
  if (!isBoardFormat(value)) throw new Error(`"${value}" is not a board format (ppr, half, std).`);
  return value;
}

function header(format: BoardFormat, seasonsWithRows: readonly number[]): string {
  if (format === DEFAULT_BOARD_FORMAT) {
    return `import type { MarketCurvePriors } from "./curve";

/**
 * GENERATED by \`npm run projections:market:fit\`. Do not edit by hand.
 *
 * Fit on ADP boards ${BENCHMARK_BOARD_FLOOR}-${MARKET_CURVE_TRAIN_CUTOFF_SEASON} inclusive and on
 * nothing else. \`fitMarketCurve\` throws if handed a season after \`MARKET_CURVE_TRAIN_CUTOFF_SEASON\`.
 * The lower bound is the earliest season this store holds a published ADP board for
 * (\`BENCHMARK_BOARD_FLOOR\`), not a choice this fit makes for itself.
 */
`;
  }
  const spec = BOARD_FORMAT_SPECS[format];
  return `import type { MarketCurvePriors } from "./curve";

/**
 * GENERATED by \`npm run projections:market:fit -- --format=${format}\`. Do not edit by hand.
 *
 * THE ${spec.label.toUpperCase()} MARKET CURVE (the scoring-formats round, 2026-09-08): the same isotonic fit
 * \`curve-fitted.ts\` carries for PPR, over the publisher's own ${spec.label} boards
 * (\`${spec.adpSource}\`) with each season's outcome scored under ${spec.label} rules, so a
 * ${spec.label} draft slot maps to ${spec.label} points. Fit on the seasons the store holds that
 * board for inside the structural cutoff: ${seasonsWithRows.join(", ")} (${seasonsWithRows.length} of the
 * ${trainSeasons().length} seasons the PPR fit pools; the feed published no ${spec.label} board before
 * ${seasonsWithRows[0]}). \`fitMarketCurve\` throws if handed a season after
 * \`MARKET_CURVE_TRAIN_CUTOFF_SEASON\`. Held out: 2023 and 2024, reported in
 * \`docs/research/2026-09-08-scoring-format-boards.md\`.
 */
`;
}

function render(format: BoardFormat, seasonsWithRows: readonly number[], priors: MarketCurvePriors): string {
  return `${header(format, seasonsWithRows)}
export const ${OUTPUTS[format].constant}: MarketCurvePriors = ${JSON.stringify(priors, null, 2)};
`;
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const format = parseFormat(process.argv.slice(2));
  const spec = BOARD_FORMAT_SPECS[format];
  const db = createDb(requireEnv("DATABASE_URL"));

  const seasons = trainSeasons();
  const seasonsWithRows: number[] = [];
  console.log(`MARKET CURVE (${spec.label}, ${spec.adpSource}), ADP boards for seasons ${seasons.join(", ")}`);
  for (const season of seasons) {
    const board = await preseasonRankingsAsOf(db, { season, source: spec.adpSource, asOf: FINAL_OUTCOME });
    console.log(`  ${season}: ${board.length} ${spec.adpSource} rows in the store`);
    if (board.length > 0) seasonsWithRows.push(season);
  }
  if (seasonsWithRows.length === 0) throw new Error(`The store holds no ${spec.adpSource} board for any train season; ingest one first.`);

  const observations = await loadMarketCurveObservations(db, seasonsWithRows, { adpSource: spec.adpSource, rules: spec.rules });
  await db.$client.end();

  console.log(`\nfit on ${observations.length} (player, season) ADP observations across seasons ${seasonsWithRows.join(", ")}`);
  const priors = fitMarketCurve(observations, { heldOutSeasons: [] });

  for (const position of POSITIONS) {
    const knots = priors[position];
    const n = observations.filter((o) => o.position === position).length;
    console.log(`\n  ${position}  (n=${n} player-seasons, ${knots.length} fitted ranks)`);
    console.log(
      `    sanity: ${SANITY_RANKS.map((rank) => `rank ${rank} = ${marketCurve(position, rank, priors).toFixed(1)}pts`).join("   ")}`,
    );
  }

  const rendered = render(format, seasonsWithRows, priors);
  const output = OUTPUTS[format].path;

  if (check) {
    const committed = readFileSync(output, "utf-8");
    if (committed !== rendered) {
      console.error(`\n${output} does not match the fitted curve. Run \`npm run projections:market:fit -- --format=${format}\` and commit the result.`);
      process.exit(1);
    }
    console.log(`\n${output} matches the fitted curve. No drift.`);
    return;
  }

  writeFileSync(output, rendered);
  console.log(`\nwrote ${output}`);
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
