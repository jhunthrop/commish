// Ingests nflverse's whole draft-pick history and fits the draft-capital rookie curve, generating
// the committed `src/projections/preseason/rookie-curve-fitted.ts`.
// Run: npm run projections:rookie-curve:fit
//      npm run projections:rookie-curve:fit -- --check   (recomputes, exits 1 on any drift)
//
// TRAIN SEASONS: `HISTORICAL_ROSTER_FLOOR` (2013) through `ROOKIE_CURVE_TRAIN_CUTOFF_SEASON` (2021),
// inclusive. The lower bound is not this script's own choice — it is the floor this repository's
// weekly stat lines are actually backfilled to (probed directly against the local store below; see
// `HISTORICAL_ROSTER_FLOOR`'s own docblock for why the roster and stat-line backfills share it). The
// upper bound IS this task's own choice, fixed at 2021 by the brief and enforced structurally:
// `fitRookieCurve` throws if handed a season past it, so a mistake here fails loudly rather than
// quietly leaking a later class into the fit.
//
// nflverse's `draft_picks` release is one file for the whole history (no season parameter), so this
// script ingests it once, unconditionally, before fitting — idempotent, exactly like every other
// writer in this engine (`recordDraftPicks`'s `onConflictDoNothing`), so re-running this script never
// duplicates a pick.
import { readFileSync, writeFileSync } from "node:fs";
import { createDb } from "@/db/client";
import { ingestDraftPicks } from "@/projections/nflverse/draft-picks";
import { HISTORICAL_ROSTER_FLOOR } from "@/projections/nflverse/rosters";
import { fitRookieCurve, loadRookieCurveObservations, rookieCurve, ROOKIE_CURVE_TRAIN_CUTOFF_SEASON } from "@/projections/preseason/rookie-curve";

const OUTPUT = "src/projections/preseason/rookie-curve-fitted.ts";
const POSITIONS = ["QB", "RB", "WR", "TE"] as const;
const SANITY_PICKS = [1, 32, 100] as const;

function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") {
    throw new Error(`${name} is not set. Run this through \`npm run projections:rookie-curve:fit\`, which loads .env.local.`);
  }
  return value;
}

function trainSeasons(): readonly number[] {
  const seasons: number[] = [];
  for (let season = HISTORICAL_ROSTER_FLOOR; season <= ROOKIE_CURVE_TRAIN_CUTOFF_SEASON; season += 1) seasons.push(season);
  return seasons;
}

function header(): string {
  return `import type { RookieCurvePriors } from "./rookie-curve";

/**
 * GENERATED by \`npm run projections:rookie-curve:fit\`. Do not edit by hand.
 *
 * Fit on rookie classes ${HISTORICAL_ROSTER_FLOOR}-${ROOKIE_CURVE_TRAIN_CUTOFF_SEASON} inclusive and
 * on nothing else. \`fitRookieCurve\` throws if handed a season after
 * \`ROOKIE_CURVE_TRAIN_CUTOFF_SEASON\`. The lower bound is the floor this repository's weekly stat
 * lines are backfilled to (\`HISTORICAL_ROSTER_FLOOR\`), not a choice this fit makes for itself.
 */
`;
}

function render(priors: import("@/projections/preseason/rookie-curve").RookieCurvePriors): string {
  return `${header()}
export const FITTED_ROOKIE_CURVE: RookieCurvePriors = ${JSON.stringify(priors, null, 2)};
`;
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const db = createDb(requireEnv("DATABASE_URL"));

  const ingestReport = await ingestDraftPicks(db);
  console.log(
    `draft_picks: ${ingestReport.entriesRead} picks read, ${ingestReport.written} new, ` +
      `${ingestReport.unknownToUniverse} unknown to the universe`,
  );

  const seasons = trainSeasons();
  const observations = await loadRookieCurveObservations(db, seasons);
  await db.$client.end();

  console.log(`\nROOKIE CURVE, fit on ${observations.length} rookie-season observations across seasons ${seasons.join(", ")}`);
  const priors = fitRookieCurve(observations, { heldOutSeasons: [] });

  for (const position of POSITIONS) {
    const knots = priors[position];
    const n = observations.filter((o) => o.position === position).length;
    console.log(`\n  ${position}  (n=${n} rookie-seasons, ${knots.length} fitted picks)`);
    console.log(
      `    sanity: ${SANITY_PICKS.map((pick) => `pick ${pick} = ${rookieCurve(position, pick, priors).toFixed(1)}pts`).join("   ")}`,
    );
  }

  const rendered = render(priors);

  if (check) {
    const committed = readFileSync(OUTPUT, "utf-8");
    if (committed !== rendered) {
      console.error(`\n${OUTPUT} does not match the fitted curve. Run \`npm run projections:rookie-curve:fit\` and commit the result.`);
      process.exit(1);
    }
    console.log(`\n${OUTPUT} matches the fitted curve. No drift.`);
    return;
  }

  writeFileSync(OUTPUT, rendered);
  console.log(`\nwrote ${OUTPUT}`);
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
