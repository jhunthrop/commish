// Fits the kicker and team-defence component priors and their two per-game variance cells, and
// generates the committed `src/projections/preseason/kdef-fitted.ts`.
// Run: npm run projections:kdef:fit [season ...]   (defaults to 2013 through 2024)
//
// FIT ON 2013 THROUGH 2024 AND ON NOTHING ELSE. 2025 is the single judgment season
// (`scripts/kdef-judgment.ts`, preregistered before it is ever read) and 2026 is the held-out data
// year. Both are passed to every fit as `heldOutSeasons`, so a fit handed one THROWS rather than
// filtering it out quietly — a parameter fitted on a season it is later scored on is not a
// measurement, and a silent filter is how that happens without anybody noticing.
//
// A DEVELOPMENT WINDOW IS A DELIBERATE ARGUMENT, NOT AN ACCIDENT. Passing 2013 through 2023 holds
// 2024 out as well, which is how the model was iterated on before the single 2025 run. Every such
// iteration is recorded in the build ledger before the judgment is taken.
import { writeFileSync } from "node:fs";
import { createDb } from "@/db/client";
import { PPR_SCORING } from "@/domain/scoring";
import { fitGameVariance, type GameVarianceObservation, type GameVariancePriors } from "@/projections/preseason/game-variance";
import { loadKdefHistory } from "@/projections/preseason/kdef-history";
import { fitKickerPriors, kickerWeeklyPoints, type KickerPriors } from "@/projections/preseason/kicker";
import { kickingWeekRowsForSeasons } from "@/projections/nflverse/kicking-weeks";
import { defenseWeeklyPoints, fitDefensePriors, type DefensePriors } from "@/projections/preseason/team-defense";

const OUTPUT = "src/projections/preseason/kdef-fitted.ts";
const FIRST_FIT_SEASON = 2013;
const LAST_FIT_SEASON = 2024;
/** 2025 is judged exactly once and 2026 is never read. Both are refused by every fit below. */
const HELD_OUT_SEASONS = [2025, 2026];

const REQUESTED = process.argv.slice(2).map(Number);
const FIT_SEASONS =
  REQUESTED.length > 0
    ? REQUESTED
    : Array.from({ length: LAST_FIT_SEASON - FIRST_FIT_SEASON + 1 }, (_, index) => FIRST_FIT_SEASON + index);

function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") {
    throw new Error(`${name} is not set. Run this through \`npm run projections:kdef:fit\`, which loads .env.local.`);
  }
  return value;
}

/** Far past any correction: this script reads completed seasons only, so nothing is gated out. */
const FINAL_OUTCOME = new Date("9999-12-31T00:00:00.000Z");

/**
 * Every kicker-season's and club-season's own weekly points, as the pooled variance estimator wants
 * them. `playerClass` is `"veteran"` for every row, and that is a statement rather than a shortcut:
 * neither position has a rookie curve (`CURVE_POSITIONS` gains neither), a first-year kicker's
 * week-to-week spread is not a separately measurable population at this sample size, and a defence
 * has no rookie season at all. One cell per position, honestly labelled.
 */
function varianceObservations(
  weeklyPointsByKey: ReadonlyMap<string, readonly number[]>,
  position: "K" | "DEF",
): readonly GameVarianceObservation[] {
  return [...weeklyPointsByKey].map(([key, weeklyPoints]) => {
    const [seasonText, playerId] = key.split("|");
    return { season: Number(seasonText), playerId: playerId!, position, playerClass: "veteran" as const, weeklyPoints };
  });
}

function header(): string {
  return `import type { GameVariancePriors } from "./game-variance";
import type { KickerPriors } from "./kicker";
import type { DefensePriors } from "./team-defense";

/**
 * GENERATED by \`npm run projections:kdef:fit\`. Do not edit by hand.
 *
 * Fit on ${FIT_SEASONS[0]} through ${FIT_SEASONS[FIT_SEASONS.length - 1]} and on nothing else (the
 * 2026-09-05 kicker and team defence round). ${HELD_OUT_SEASONS.join(" and ")} are held out: 2025 is
 * judged EXACTLY ONCE by \`scripts/kdef-judgment.ts\` against the gates preregistered in
 * \`docs/research/2026-09-05-kicker-defense-preregistration.md\`, and 2026 is never read by any fit
 * or judgment at all.
 *
 * \`FITTED_KDEF_GAME_VARIANCE\` carries the K and DEF cells ONLY. The four skill positions' cells are
 * generated separately by \`npm run projections:game-variance:fit\` into
 * \`game-variance-fitted.ts\`, because that script's observation loader reads
 * \`player_week_observations\`, which holds neither of these two positions. \`fitted-variance.ts\`
 * is the one place the two halves are composed.
 */
`;
}

/**
 * The defence priors, with `leagueAllowed` rendered as one compact `[points, yards]` pair per line.
 *
 * A pretty-printed nested array puts each tuple on four lines and turns a 6,270-game distribution
 * into a 25,000-line file. The distribution itself is not negotiable — a distribution shrinkage needs
 * the games themselves, and a summary of it would be exactly the "tier of the mean" error this whole
 * module exists to avoid — so what gives is the rendering, not the data.
 */
function renderDefensePriors(defence: DefensePriors): string {
  const { leagueAllowed, ...rest } = defence;
  const body = Object.entries(rest)
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join("\n");
  const allowed = leagueAllowed.map((pair) => `    [${pair[0]}, ${pair[1]}],`).join("\n");
  return `{\n${body}\n  "leagueAllowed": [\n${allowed}\n  ],\n}`;
}

function render(kicker: KickerPriors, defence: DefensePriors, variance: GameVariancePriors): string {
  return `${header()}
export const FITTED_KICKER_PRIORS: KickerPriors = ${JSON.stringify(kicker, null, 2)};

export const FITTED_DEFENSE_PRIORS: DefensePriors = ${renderDefensePriors(defence)};

export const FITTED_KDEF_GAME_VARIANCE: GameVariancePriors = ${JSON.stringify(variance, null, 2)};
`;
}

async function main(): Promise<void> {
  for (const season of FIT_SEASONS) {
    if (HELD_OUT_SEASONS.includes(season)) {
      throw new Error(
        `${season} is held out and cannot be fitted on. 2025 is judged exactly once and 2026 is never read.`,
      );
    }
  }

  const db = createDb(requireEnv("DATABASE_URL"));
  const history = await loadKdefHistory(db, FIT_SEASONS, FINAL_OUTCOME);
  const kickingRows = await kickingWeekRowsForSeasons(db, FIT_SEASONS);
  await db.$client.end();

  if (history.defenseGamesWithoutScore > 0) {
    console.warn(
      `WARNING: ${history.defenseGamesWithoutScore} archived defence rows had no game score in the store and were DROPPED, ` +
        `never zeroed. Run \`npm run projections:schedule:points-allowed\` before trusting this fit.`,
    );
  }

  const kicker = fitKickerPriors(history.kickerSeasons, { heldOutSeasons: HELD_OUT_SEASONS });
  const defence = fitDefensePriors(history.defenseGames, { heldOutSeasons: HELD_OUT_SEASONS });
  const variance = fitGameVariance(
    [
      ...varianceObservations(kickerWeeklyPoints(kickingRows, PPR_SCORING), "K"),
      ...varianceObservations(defenseWeeklyPoints(history.defenseGames, PPR_SCORING), "DEF"),
    ],
    { heldOutSeasons: HELD_OUT_SEASONS, positions: ["K", "DEF"] },
  );

  console.log(`\n${"=".repeat(92)}`);
  console.log(`KICKER AND TEAM DEFENCE COMPONENT FIT, ${FIT_SEASONS[0]} to ${FIT_SEASONS[FIT_SEASONS.length - 1]}`);
  console.log(`${"=".repeat(92)}\n`);
  console.log(`kicker seasons                      ${history.kickerSeasons.length}`);
  console.log(`distinct kickers                    ${new Set(history.kickerSeasons.map((entry) => entry.playerId)).size}`);
  console.log(`defence games                       ${history.defenseGames.length}`);
  console.log(`defence games with no score         ${history.defenseGamesWithoutScore}`);

  console.log("\nKICKER LEAGUE MEANS");
  console.log(`  field goal attempts a game        ${kicker.leagueFieldGoalAttemptsPerGame.toFixed(4)}`);
  console.log(`  extra point attempts a game       ${kicker.leagueExtraPointAttemptsPerGame.toFixed(4)}`);
  console.log(`  field goal make rate              ${kicker.leagueFieldGoalMakeRate.toFixed(4)}`);
  console.log(`  extra point make rate             ${kicker.leagueExtraPointMakeRate.toFixed(4)}`);
  console.log(`  share of club games played        ${kicker.leagueGamesRate.toFixed(4)}`);
  console.log(`  recency decay (searched)          ${kicker.recencyDecay}`);
  console.log(
    `  projection error variance         ${kicker.projectionErrorVariance.toFixed(1)} (sd ${Math.sqrt(kicker.projectionErrorVariance).toFixed(1)} season points)`,
  );

  console.log("\nTEAM DEFENCE LEAGUE MEANS, per game");
  for (const [component, value] of Object.entries(defence.leaguePerGame)) {
    console.log(`  ${component.padEnd(34)}${value.toFixed(4)}`);
  }
  const points = defence.leagueAllowed.map((allowed) => allowed[0]);
  const yards = defence.leagueAllowed.map((allowed) => allowed[1]);
  const mean = (values: readonly number[]): number => values.reduce((total, value) => total + value, 0) / values.length;
  console.log(`  points allowed a game             ${mean(points).toFixed(4)} over ${points.length} games`);
  console.log(`  yards allowed a game              ${mean(yards).toFixed(4)}`);
  console.log(`  recency decay (searched)          ${defence.recencyDecay}`);
  console.log(
    `  projection error variance         ${defence.projectionErrorVariance.toFixed(1)} (sd ${Math.sqrt(defence.projectionErrorVariance).toFixed(1)} season points)`,
  );

  console.log("\nPER-GAME VARIANCE (points squared)");
  for (const position of ["K", "DEF"] as const) {
    const value = variance.veteran[position];
    console.log(`  ${position.padEnd(34)}${value === undefined ? "not measured" : `${value.toFixed(2)} (sd ${Math.sqrt(value).toFixed(2)})`}`);
  }

  writeFileSync(OUTPUT, render(kicker, defence, variance));
  console.log(`\nwrote ${OUTPUT}`);
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
