// Fits the preseason model's own parameters on the FIT seasons and generates the committed
// `src/projections/preseason/fitted.ts`.
// Run: npm run projections:preseason:fit
//
// Two parameter sets, both fitted the way `projection-fit.ts` fits the weekly model's: on 2021 and
// 2022 only, with the held-out seasons named explicitly so `fit.ts` throws rather than quietly
// reading one. The output is generated into a committed file so that "what did the engine believe
// when it said that" is answerable from the repository alone, with no database and no network.
//
// It prints the whole fit before writing it, because a table of sixteen availability cells and
// twenty-four rookie cells is a set of claims a reader should be able to disagree with, and a
// generated file nobody ever reads is a set of claims nobody ever checked.
import { writeFileSync } from "node:fs";
import { createDb } from "@/db/client";
import { FIT_SEASONS, HELD_OUT_SEASONS } from "@/projections/model/fitted";
import { FITTED_MODEL } from "@/projections/model/source";
import { AGE_BRACKETS, ROLE_BRACKETS, expectedGamesPlayed } from "@/projections/preseason/availability";
import {
  fitAvailabilityPriors,
  fitCareerPriors,
  fitDepthPriors,
  fitRookieGameRate,
  fitRookiePriors,
  ROOKIE_DURABILITY_HELD_OUT_SEASONS,
  ROOKIE_DURABILITY_TRAIN_SEASONS,
} from "@/projections/preseason/fit";
import { DEPTH_RANKS, depthMultiplier } from "@/projections/preseason/depth";
import { EXPERIENCE_BANDS, careerMultiplier } from "@/projections/preseason/career";
import { DRAFT_BUCKETS, draftBucketFor } from "@/projections/preseason/rookies";
import {
  loadAvailabilityObservations,
  loadCareerObservations,
  loadDepthObservations,
  loadRookieObservations,
} from "@/projections/preseason/source";

const OUTPUT = "src/projections/preseason/fitted.ts";
const POSITIONS = ["QB", "RB", "WR", "TE"] as const;

function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") {
    throw new Error(`${name} is not set. Run this through \`npm run projections:preseason:fit\`, which loads .env.local.`);
  }
  return value;
}

function header(): string {
  return `import type { AvailabilityPriors } from "./availability";
import type { CareerPriors } from "./career";
import type { DepthPriors } from "./depth";
import type { RookiePriors } from "./rookies";

/**
 * GENERATED by \`npm run projections:preseason:fit\`. Do not edit by hand.
 *
 * Committed rather than computed at startup, for the reason \`model/fitted.ts\` is: what the engine
 * believed when it published a board has to be answerable from the repository alone, with no
 * database and no network. A parameter that lives only in a fitting run is a parameter no reviewer
 * can check and no bisect can recover.
 *
 * Fitted on ${FIT_SEASONS.join(" and ")} and on nothing else. ${HELD_OUT_SEASONS.join(" and ")} are held out and
 * \`fitAvailabilityPriors\` throws if it is handed either.
 *
 * ONE EXCEPTION: \`FITTED_ROOKIE_PRIORS.gameRate\` — the rookie DURABILITY prior — is fitted on
 * \`${ROOKIE_DURABILITY_TRAIN_SEASONS.join(" and ")}\` instead (calibration fix round, 2026-09-04, Task 1),
 * with \`${ROOKIE_DURABILITY_HELD_OUT_SEASONS.join(" and ")}\` held out. Every other field of
 * \`FITTED_ROOKIE_PRIORS\` (\`byBucket\`, \`typicalIncumbentClaim\`, ...) is still fitted on
 * ${FIT_SEASONS.join(" and ")}. See \`fit.ts\`'s \`fitRookieGameRate\` docblock for why.
 */
`;
}

async function main(): Promise<void> {
  const db = createDb(requireEnv("DATABASE_URL"));

  const availabilityObservations = await loadAvailabilityObservations(db, FIT_SEASONS);
  const availability = fitAvailabilityPriors(availabilityObservations, { heldOutSeasons: HELD_OUT_SEASONS });
  const rookieObservations = await loadRookieObservations(db, FIT_SEASONS, FITTED_MODEL);
  const rookiesWithSharesWindowGameRate = fitRookiePriors(rookieObservations, {
    heldOutSeasons: HELD_OUT_SEASONS,
    leagueTeamVolume: FITTED_MODEL.opportunity.leagueTeamVolume,
  });
  // THE DURABILITY PRIOR (calibration fix round, 2026-09-04, Task 1) gets its OWN, fresher fit
  // window — 2023-2024 rather than the shares table's 2021-2022 — and REPLACES the `gameRate` field
  // `fitRookiePriors` just produced above. See `fit.ts`'s `fitRookieGameRate` docblock for why the
  // window differs, and `ROOKIE_DURABILITY_TRAIN_SEASONS`/`ROOKIE_DURABILITY_HELD_OUT_SEASONS` for
  // the register discipline (fit 2023-2024, score 2025, 2026 never touched) this calibration round
  // reports under.
  const durabilityObservations = await loadRookieObservations(db, ROOKIE_DURABILITY_TRAIN_SEASONS, FITTED_MODEL);
  const durabilityGameRate = fitRookieGameRate(durabilityObservations, {
    heldOutSeasons: ROOKIE_DURABILITY_HELD_OUT_SEASONS,
  });
  const rookies = { ...rookiesWithSharesWindowGameRate, gameRate: durabilityGameRate };

  const depthObservations = await loadDepthObservations(db, FIT_SEASONS, FITTED_MODEL);
  const depth = fitDepthPriors(depthObservations, { heldOutSeasons: HELD_OUT_SEASONS });

  // LAST, and it has to be: the career curve is fitted against the board this fit has just produced
  // with every other feature on and the curve off. Fitting it against a bare model would measure the
  // residual of a board nobody publishes.
  const careerObservations = await loadCareerObservations(db, FIT_SEASONS, {
    model: FITTED_MODEL,
    availability,
    rookies,
    depth,
  });
  const career = fitCareerPriors(careerObservations, { heldOutSeasons: HELD_OUT_SEASONS });

  console.log(`AVAILABILITY, fitted on ${availabilityObservations.length} player-seasons\n`);
  console.log(`  share of the season played, by ROLE`);
  console.log(`  ${"".padEnd(4)} ${ROLE_BRACKETS.map((bracket) => bracket.padStart(10)).join(" ")}`);
  for (const position of POSITIONS) {
    console.log(
      `  ${position.padEnd(4)} ${ROLE_BRACKETS.map((bracket) => availability.baseline[position][bracket].toFixed(3).padStart(10)).join(" ")}`,
    );
  }
  console.log(`\n  multiplied by AGE`);
  console.log(`  ${"".padEnd(4)} ${AGE_BRACKETS.map((bracket) => bracket.padStart(10)).join(" ")}`);
  for (const position of POSITIONS) {
    console.log(
      `  ${position.padEnd(4)} ${AGE_BRACKETS.map((bracket) => availability.ageMultiplier[position][bracket].toFixed(3).padStart(10)).join(" ")}`,
    );
  }
  console.log(
    `\n  status multipliers  ${Object.entries(availability.statusMultiplier)
      .map(([status, value]) => `${status} ${value.toFixed(3)}`)
      .join("  ")}`,
  );
  console.log(
    `  shrinkage ${availability.priorGames} team-games of prior, recency decay ${availability.recencyDecay}, ` +
      `history ${availability.historySeasons} seasons`,
  );
  console.log(
    `  spread: concentration ${availability.concentration.toFixed(2)} plus ${availability.concentrationPerSeason.toFixed(2)} per season of record`,
  );
  // The sanity check the role term exists for, printed so a bad fit announces itself rather than
  // quietly shipping a board that fades every starter in the league.
  console.log("\n  a full-time starter with three clean seasons, by position:");
  for (const position of POSITIONS) {
    const outlook = expectedGamesPlayed(
      {
        position,
        age: 26,
        status: "active",
        projectedSnapShare: position === "RB" ? 0.65 : 0.9,
        history: [2023, 2022, 2021].map((season) => ({ season, gamesPlayed: 17, teamGames: 17 })),
        baselineRate: null,
      },
      { season: 2024, priors: availability },
    );
    console.log(
      `    ${position.padEnd(4)} ${outlook.expected.toFixed(1)} games (floor ${outlook.distribution.floor}, ceiling ${outlook.distribution.ceiling})`,
    );
  }

  console.log(`\nROOKIES, fitted on ${rookieObservations.length} rookie-seasons`);
  for (const position of POSITIONS) {
    console.log(`\n  ${position}  (snap / target / carry / pass-attempt share, per game played)`);
    for (const bucket of DRAFT_BUCKETS) {
      const cell = rookies.byBucket[position][bucket];
      const count = rookieObservations.filter(
        (observation) => observation.position === position && observation.shares !== null,
      ).length;
      console.log(
        `    ${bucket.padEnd(11)} ${cell.snapShare.toFixed(3)}  ${cell.targetShare.toFixed(3)}  ` +
          `${cell.carryShare.toFixed(3)}  ${cell.passAttemptShare.toFixed(3)}${bucket === "round1" ? `   (n=${count} played at ${position})` : ""}`,
      );
    }
    console.log(`    typical incumbent claim ${rookies.typicalIncumbentClaim[position].toFixed(3)}`);
  }

  console.log(`\nROOKIE DURABILITY (gameRate), fitted separately on ${durabilityObservations.length} rookie-seasons (${ROOKIE_DURABILITY_TRAIN_SEASONS.join("-")})`);
  for (const position of POSITIONS) {
    const counts = DRAFT_BUCKETS.map(
      (bucket) => durabilityObservations.filter((o) => o.position === position && draftBucketFor(o.overallPick) === bucket).length,
    );
    console.log(
      `  ${position.padEnd(4)} ${DRAFT_BUCKETS.map((bucket, index) => `${bucket} ${durabilityGameRate[position][bucket].toFixed(3)} (n=${counts[index]})`).join("   ")}`,
    );
  }

  console.log(`\nDEPTH CHART, fitted on ${depthObservations.length} player-seasons`);
  console.log(`  a multiplier on layer 1's snap share, normalised within the position`);
  console.log(`  ${"".padEnd(4)} ${DEPTH_RANKS.map((rank) => rank.padStart(12)).join(" ")}`);
  for (const position of POSITIONS) {
    const counts = DEPTH_RANKS.map(
      (rank) => depthObservations.filter((o) => o.position === position && o.rank === rank).length,
    );
    console.log(
      `  ${position.padEnd(4)} ${DEPTH_RANKS.map((rank, index) => `${depthMultiplier(position, rank, depth).toFixed(3)} (n=${String(counts[index]).padStart(3)})`.padStart(12)).join(" ")}`,
    );
  }

  console.log(`\nCAREER STAGE, fitted on ${careerObservations.length} player-seasons (absentees at zero)`);
  console.log(`  a multiplier on projected per-game production, normalised within the position`);
  console.log(`  ${"".padEnd(4)} ${EXPERIENCE_BANDS.map((band) => band.padStart(14)).join(" ")}`);
  for (const position of POSITIONS) {
    const counts = EXPERIENCE_BANDS.map(
      (band) => careerObservations.filter((o) => o.position === position && o.band === band).length,
    );
    console.log(
      `  ${position.padEnd(4)} ${EXPERIENCE_BANDS.map((band, index) => `${careerMultiplier(position, band, career).toFixed(3)} (n=${String(counts[index]).padStart(3)})`.padStart(14)).join(" ")}`,
    );
  }

  writeFileSync(
    OUTPUT,
    `${header()}
export const FITTED_AVAILABILITY_PRIORS: AvailabilityPriors = ${JSON.stringify(availability, null, 2)};

export const FITTED_ROOKIE_PRIORS: RookiePriors = ${JSON.stringify(rookies, null, 2)};

export const FITTED_DEPTH_PRIORS: DepthPriors = ${JSON.stringify(depth, null, 2)};

export const FITTED_CAREER_PRIORS: CareerPriors = ${JSON.stringify(career, null, 2)};
`,
  );
  console.log(`\nwrote ${OUTPUT}`);

  await db.$client.end();
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
