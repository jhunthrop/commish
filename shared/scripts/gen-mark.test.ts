// The mark's generator: the web's whistle (web/src/lib/ui/mark.ts) into the iOS app's drawing
// commands. Run with `node --test shared/scripts/*.test.ts`.
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { parsePath, renderMarkSwift, type Segment } from './gen-mark.ts';

const near = (a: number, b: number): boolean => Math.abs(a - b) < 1e-6;

void test('moves, lines and the close read as themselves', () => {
	assert.deepEqual(parsePath('M1 2 L3 4 Z'), [
		{ kind: 'move', x: 1, y: 2 },
		{ kind: 'line', x: 3, y: 4 },
		{ kind: 'close' }
	]);
});

void test('an arc becomes cubic curves that end on its end point, a quarter turn or less each', () => {
	// A half circle of radius 10 centred on the origin, from (10, 0) to (-10, 0), sweeping through +y.
	const segments = parsePath('M10 0 A10 10 0 0 1 -10 0');
	const curves = segments.filter(
		(s): s is Extract<Segment, { kind: 'curve' }> => s.kind === 'curve'
	);
	assert.equal(curves.length, 2);
	const last = curves.at(-1);
	assert.ok(last && near(last.x, -10) && near(last.y, 0), JSON.stringify(last));
	// The first quarter ends at the bottom of the circle (y down), (0, 10).
	assert.ok(
		near(curves[0]?.x ?? NaN, 0) && near(curves[0]?.y ?? NaN, 10),
		JSON.stringify(curves[0])
	);
});

void test('a radius too short for its end points grows until it spans them, as SVG says', () => {
	const segments = parsePath('M0 0 A1 1 0 0 1 10 0');
	const last = segments.at(-1);
	assert.ok(last?.kind === 'curve' && near(last.x, 10) && near(last.y, 0), JSON.stringify(last));
});

void test('the Swift names the box, the disc, the strokes and one command per segment', () => {
	const swift = renderMarkSwift({
		path: 'M0 0 L10 0 Z',
		box: 256,
		disc: { cx: 1, cy: 2, r: 3 },
		stroke: 11.4,
		smallStroke: 18.2,
		smallMax: 40
	});
	assert.match(swift, /^\/\/ Generated by shared\/scripts\/gen-mark\.ts/);
	assert.match(swift, /public static let box: Double = 256/);
	assert.match(swift, /public static let disc = MarkDisc\(cx: 1, cy: 2, r: 3\)/);
	assert.match(swift, /public static let stroke: Double = 11\.4/);
	assert.match(swift, /\.move\(x: 0, y: 0\),\n\s+\.line\(x: 10, y: 0\),\n\s+\.close,/);
	assert.doesNotMatch(swift, /import SwiftUI/);
});

void test('an unknown command fails with its letter', () => {
	assert.throws(() => parsePath('M0 0 Q1 1 2 2'), /Q/);
});
