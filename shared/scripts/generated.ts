/** What every generator under shared/scripts shares: the repository root, the outputs a generator
 * returns (a repository path to its text) and how they land on disk. A generator's `generate()` is
 * pure of the disk it writes, so check-gen.ts can regenerate into a temp dir and compare. */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

/** The repository root, two folders above this file. */
export const REPOSITORY = resolve(import.meta.dirname, '../..');

/** A generator's files: each repository-relative path and its full text. */
export type Outputs = ReadonlyMap<string, string>;

/** The first line of a generated source file, in the comment syntax of its language. */
export function generatedBy(script: string, source: string): string {
	return `Generated by ${script} from ${source}. Do not edit: edit the source and run \`npm run gen:shared\` in web/.`;
}

/** Writes each output under `root` (the repository, or check-gen's temp dir). */
export async function writeOutputs(outputs: Outputs, root: string = REPOSITORY): Promise<void> {
	await Promise.all(
		[...outputs].map(async ([path, text]) => {
			const file = join(root, path);
			await mkdir(dirname(file), { recursive: true });
			await writeFile(file, text);
		})
	);
}

/** The two app languages a generator writes. */
export type AppLanguage = 'swift' | 'kotlin';

/** A Swift or Kotlin string literal: the text in double quotes, its backslashes, quotes and line
 * breaks escaped, as both languages read them, and in Kotlin its dollar signs, which would open a
 * template (Swift has no `\$` escape and no `$` template, so it keeps them). */
export function stringLiteral(text: string, language: AppLanguage): string {
	const escaped = text
		.replace(/\\/g, '\\\\')
		.replace(/"/g, '\\"')
		.replace(/\n/g, '\\n')
		.replace(/\r/g, '\\r')
		.replace(/\t/g, '\\t');
	return `"${language === 'kotlin' ? escaped.replace(/\$/g, '\\$') : escaped}"`;
}
