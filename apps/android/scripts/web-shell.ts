/**
 * The Android app's shell from the web's own sources, never hand-copied:
 * - the whistle (web/src/lib/ui/mark.ts): MarkShape.generated.kt for the Mark composable, and the
 *   launcher icon as an adaptive icon on the dark page colour (as web/scripts/app-icons.ts draws the
 *   maskable icon);
 * - the window colour of each theme (web/src/lib/site/app-manifest.ts APP_COLORS);
 * - the bottom bar (web/src/lib/ui/rail-order.ts railOfKey, RAIL_WITHOUT_LEAGUE, railShown): each
 *   phase's phone five and the bar with no league by the site's season, with the web's labels
 *   (run/week-names.ts railItemLabel), in Rail.generated.kt, and each rail glyph
 *   (web/src/lib/ui/rail-icons.ts) as a vector drawable in the icon set's style (24 grid, 1.8
 *   stroke, round caps and joins).
 *
 *   node apps/android/scripts/web-shell.ts           write the files
 *   node apps/android/scripts/web-shell.ts --check   exit 1 when a committed file differs (CI)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { APP_COLORS } from '../../../web/src/lib/site/app-manifest.ts';
import { ICONS, type IconName, type IconShape } from '../../../web/src/lib/ui/icons.ts';
import {
	MARK_BOX,
	MARK_COLORS,
	MARK_DISC,
	MARK_PATH,
	MARK_SMALL_MAX,
	MARK_SMALL_STROKE,
	MARK_STROKE,
	MARK_VIEW_SIDE
} from '../../../web/src/lib/ui/mark.ts';
import { railItemLabel } from '../../../web/src/lib/run/week-names.ts';
import { LEAGUE_PHASES, RAIL_FOOT, railKey, railPhase, type SitePhase } from '../../../web/src/lib/ui/nav.ts';
import { RAIL_ICONS, type RailIconName } from '../../../web/src/lib/ui/rail-icons.ts';
import { RAIL_WITHOUT_LEAGUE, railOfKey, railShown, type RailEntry } from '../../../web/src/lib/ui/rail-order.ts';

const ANDROID = resolve(import.meta.dirname, '..');
const HEADER = 'Generated by apps/android/scripts/web-shell.ts from the web. Do not edit: edit the web and run the script.';

/** An adaptive icon's side in dp, and the share of it the whistle's length spans (the web's maskable
 * scale: the whistle and its outline inside the centre a mask never cuts). */
const ICON_DP = 108;
const MASKABLE_SCALE = 0.57;
/** The icon set's grid and stroke (web/src/lib/ui/icons.ts). */
const GLYPH_GRID = 24;
const GLYPH_STROKE = 1.8;

const argb = (hex: string): string => `#FF${hex.slice(1).toUpperCase()}`;
const quote = (text: string): string => JSON.stringify(text);

function markKotlin(): string {
	return `// ${HEADER}
@file:Suppress("ktlint", "MagicNumber")

package app.trycommish.design

/** The whistle as the web draws it: the trace's box, the outline's path, the pea and the weights. */
object MarkShape {
    const val BOX: Float = ${MARK_BOX}f
    const val VIEW_SIDE: Float = ${MARK_VIEW_SIDE}f
    const val PATH: String = "${MARK_PATH}"
    const val PEA_X: Float = ${MARK_DISC.cx}f
    const val PEA_Y: Float = ${MARK_DISC.cy}f
    const val PEA_R: Float = ${MARK_DISC.r}f
    const val STROKE: Float = ${MARK_STROKE}f
    const val SMALL_STROKE: Float = ${MARK_SMALL_STROKE}f
    const val SMALL_MAX_DP: Float = ${MARK_SMALL_MAX}f
}
`;
}

/** A circle as path data: two half arcs. */
const circlePath = (cx: number, cy: number, r: number): string =>
	`M${String(cx - r)},${String(cy)} a${String(r)},${String(r)} 0 1,0 ${String(2 * r)},0 a${String(r)},${String(r)} 0 1,0 ${String(-2 * r)},0`;

/** A rounded rectangle as path data. */
function rectPath(x: number, y: number, w: number, h: number, rx: number): string {
	const s = (n: number): string => String(n);
	return (
		`M${s(x + rx)},${s(y)} h${s(w - 2 * rx)} a${s(rx)},${s(rx)} 0 0,1 ${s(rx)},${s(rx)} v${s(h - 2 * rx)} ` +
		`a${s(rx)},${s(rx)} 0 0,1 ${s(-rx)},${s(rx)} h${s(-(w - 2 * rx))} a${s(rx)},${s(rx)} 0 0,1 ${s(-rx)},${s(-rx)} ` +
		`v${s(-(h - 2 * rx))} a${s(rx)},${s(rx)} 0 0,1 ${s(rx)},${s(-rx)} z`
	);
}

function shapePath(shape: IconShape): string {
	if (shape.tag === 'path') return shape.d;
	if (shape.tag === 'circle') return circlePath(shape.cx, shape.cy, shape.r);
	return rectPath(shape.x, shape.y, shape.width, shape.height, shape.rx);
}

function foreground(): string {
	// The viewport is the icon in the trace's units: the whistle's length (MARK_BOX) spans the scale.
	const viewport = MARK_BOX / MASKABLE_SCALE;
	const offset = (viewport - MARK_BOX) / 2;
	const fixed = (n: number): string => n.toFixed(2);
	return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${String(ICON_DP)}dp"
    android:height="${String(ICON_DP)}dp"
    android:viewportWidth="${fixed(viewport)}"
    android:viewportHeight="${fixed(viewport)}">
    <group android:translateX="${fixed(offset)}" android:translateY="${fixed(offset)}">
        <path
            android:pathData="${MARK_PATH}"
            android:strokeColor="${argb(MARK_COLORS.dark.ink)}"
            android:strokeWidth="${String(MARK_STROKE)}"
            android:strokeLineJoin="round" />
        <path
            android:pathData="${circlePath(MARK_DISC.cx, MARK_DISC.cy, MARK_DISC.r)}"
            android:fillColor="${argb(MARK_COLORS.dark.accent)}" />
    </group>
</vector>
`;
}

function colors(theme: 'light' | 'dark'): string {
	const icon = theme === 'light' ? `\n    <color name="ic_launcher_background">${APP_COLORS.dark.page}</color>` : '';
	return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<resources>
    <color name="window_background">${APP_COLORS[theme].page}</color>${icon}
</resources>
`;
}

/** A glyph as a vector drawable, stroked in black for the composable to tint. */
function glyph(shapes: readonly IconShape[]): string {
	const paths = shapes
		.map(
			(shape) => `    <path
        android:pathData="${shapePath(shape)}"
        android:strokeColor="#FF000000"
        android:strokeWidth="${String(GLYPH_STROKE)}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />`
		)
		.join('\n');
	return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${String(GLYPH_GRID)}dp"
    android:height="${String(GLYPH_GRID)}dp"
    android:viewportWidth="${String(GLYPH_GRID)}"
    android:viewportHeight="${String(GLYPH_GRID)}">
${paths}
</vector>
`;
}

/** The phone's five of a rail. */
const phoneFive = (rail: readonly RailEntry[]): readonly RailEntry[] => rail.filter((entry) => !entry.wideOnly);

function railList(rail: readonly RailEntry[]): string {
	const items = phoneFive(rail).map(
		(e) =>
			`RailItem(${quote(e.key)}, ${quote(e.screen ?? e.section)}, ${quote(railItemLabel(e, SEASON_WEEK))}, R.drawable.rail_${e.icon})`
	);
	return `listOf(\n            ${items.join(',\n            ')},\n        )`;
}

/** The rail keys railOfKey reads: each phase, and the playoffs with the wire still open. */
const RAIL_KEYS = [...LEAGUE_PHASES, 'playoffs_waivers'] as const;

/** The top bar's, the player sheet's and the cheat sheet's glyphs from the web's icon set: the league
 * switch's mark and chevron, the search, the close, and a sheet row's tag count and note. */
const SHELL_ICONS: readonly IconName[] = ['league', 'chevron', 'search', 'close', 'tag', 'note'];

/** The site's own seasons (GET /me's season.phase), each read with no league followed. */
const SITE_PHASES: readonly SitePhase[] = ['preseason', 'in_season', 'playoffs', 'offseason'];

/** A week the season has named: an in-season rail's week item says Rankings then, as the app's bars
 * draw it whenever they show it (the item is only on the season's rails). */
const SEASON_WEEK = 1;

function railKotlin(): string {
	const phases = RAIL_KEYS.map((key) => `        ${quote(key)} to ${railList(railOfKey(key))},`).join('\n');
	const seasons = SITE_PHASES.map(
		(season) => `        ${quote(season)} to ${railList(railShown(railKey(railPhase(null, season)), false))},`
	).join('\n');
	return `// ${HEADER}
@file:Suppress("ktlint", "MaxLineLength")

package app.trycommish.design

/** One tab of the bottom bar: the web's rail key, the page it opens, its label and its glyph. */
data class RailItem(val key: String, val page: String, val label: String, val glyph: Int)

/** The phone's bottom bar per season phase, the web's (web/src/lib/ui/rail-order.ts): the five each
 * rail key shows, and the season's bar with no league selected. */
object Rail {
    /** By rail key: each league phase, and "playoffs_waivers" while the playoffs' wire is open. */
    val byKey: Map<String, List<RailItem>> = mapOf(
${phases}
    )

    /** No league selected (signed out, or none attached): RAIL_WITHOUT_LEAGUE. */
    val withoutLeague: List<RailItem> = ${railList(RAIL_WITHOUT_LEAGUE)}

    /** No league followed, by the site's season (railShown over railPhase(null, season)): the draft's
     * bar before the season and after it, the season's bar without a league in it. */
    val withoutLeagueBySeason: Map<String, List<RailItem>> = mapOf(
${seasons}
    )
}
`;
}

function outputs(): ReadonlyMap<string, string> {
	const used = new Set<RailIconName>([
		...[...RAIL_KEYS.flatMap((key) => phoneFive(railOfKey(key))), ...phoneFive(RAIL_WITHOUT_LEAGUE)].map((e) => e.icon),
		RAIL_FOOT.icon
	]);
	return new Map([
		['design/src/main/kotlin/app/trycommish/design/MarkShape.generated.kt', markKotlin()],
		['design/src/main/kotlin/app/trycommish/design/Rail.generated.kt', railKotlin()],
		...[...used].sort().map((name) => [`design/src/main/res/drawable/rail_${name}.xml`, glyph(RAIL_ICONS[name])] as const),
		...SHELL_ICONS.map((name) => [`design/src/main/res/drawable/icon_${name}.xml`, glyph(ICONS[name])] as const),
		['app/src/main/res/drawable/ic_launcher_foreground.xml', foreground()],
		['app/src/main/res/values/colors.generated.xml', colors('light')],
		['app/src/main/res/values-night/colors.generated.xml', colors('dark')]
	]);
}

async function main(check: boolean): Promise<number> {
	const files = outputs();
	const differ: string[] = [];
	for (const [path, text] of files) {
		const file = join(ANDROID, path);
		if (check) {
			const committed = await readFile(file, 'utf8').catch(() => null);
			if (committed !== text) differ.push(path);
		} else {
			await writeFile(file, text);
		}
	}
	for (const path of differ) process.stderr.write(`web-shell: apps/android/${path} differs from the web\n`);
	if (check && differ.length === 0) process.stdout.write(`web-shell: ${String(files.size)} files match the web\n`);
	return differ.length === 0 ? 0 : 1;
}

process.exitCode = await main(process.argv.includes('--check'));
