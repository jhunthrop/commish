/**
 * The Android app's mark from the web's one drawing (web/src/lib/ui/mark.ts): the whistle's path and
 * pea as Kotlin constants for the design module's Mark composable, and the launcher icon as an
 * adaptive icon (the whistle in its dark colours inside the centre a launcher's mask never cuts, on
 * the dark page colour, as the web's maskable icon is drawn by web/scripts/app-icons.ts).
 *
 *   node apps/android/scripts/mark.ts           write the files
 *   node apps/android/scripts/mark.ts --check   exit 1 when a committed file differs (CI)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { APP_COLORS } from '../../../web/src/lib/site/app-manifest.ts';
import {
	MARK_BOX,
	MARK_COLORS,
	MARK_DISC,
	MARK_PATH,
	MARK_SMALL_MAX,
	MARK_SMALL_STROKE,
	MARK_STROKE,
	MARK_VIEW_SIDE
} from '../../../web/src/lib/ui/mark.ts';

const ANDROID = resolve(import.meta.dirname, '..');
const HEADER = 'Generated by apps/android/scripts/mark.ts from web/src/lib/ui/mark.ts. Do not edit: edit the mark and run the script.';

/** An adaptive icon's side in dp, and the share of it the whistle's length spans (the web's maskable
 * scale: the whistle and its outline inside the centre a mask never cuts). */
const ICON_DP = 108;
const MASKABLE_SCALE = 0.57;

const argb = (hex: string): string => `#FF${hex.slice(1).toUpperCase()}`;

function kotlin(): string {
	return `// ${HEADER}
@file:Suppress("ktlint", "MagicNumber")

package app.trycommish.design

/** The whistle as the web draws it: the trace's box, the outline's path, the pea and the weights. */
object MarkShape {
    const val BOX: Float = ${MARK_BOX}f
    const val VIEW_SIDE: Float = ${MARK_VIEW_SIDE}f
    const val PATH: String = "${MARK_PATH}"
    const val PEA_X: Float = ${MARK_DISC.cx}f
    const val PEA_Y: Float = ${MARK_DISC.cy}f
    const val PEA_R: Float = ${MARK_DISC.r}f
    const val STROKE: Float = ${MARK_STROKE}f
    const val SMALL_STROKE: Float = ${MARK_SMALL_STROKE}f
    const val SMALL_MAX_DP: Float = ${MARK_SMALL_MAX}f
}
`;
}

function foreground(): string {
	// The viewport is the icon in the trace's units: the whistle's length (MARK_BOX) spans the scale.
	const viewport = MARK_BOX / MASKABLE_SCALE;
	const offset = (viewport - MARK_BOX) / 2;
	const { cx, cy, r } = MARK_DISC;
	const fixed = (n: number): string => n.toFixed(2);
	return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${ICON_DP}dp"
    android:height="${ICON_DP}dp"
    android:viewportWidth="${fixed(viewport)}"
    android:viewportHeight="${fixed(viewport)}">
    <group android:translateX="${fixed(offset)}" android:translateY="${fixed(offset)}">
        <path
            android:pathData="${MARK_PATH}"
            android:strokeColor="${argb(MARK_COLORS.dark.ink)}"
            android:strokeWidth="${MARK_STROKE}"
            android:strokeLineJoin="round" />
        <path
            android:pathData="M${cx - r},${cy} a${r},${r} 0 1,0 ${2 * r},0 a${r},${r} 0 1,0 ${-2 * r},0"
            android:fillColor="${argb(MARK_COLORS.dark.accent)}" />
    </group>
</vector>
`;
}

function background(): string {
	return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<resources>
    <color name="ic_launcher_background">${APP_COLORS.dark.page}</color>
</resources>
`;
}

const OUTPUTS: ReadonlyMap<string, string> = new Map([
	['design/src/main/kotlin/app/trycommish/design/MarkShape.generated.kt', kotlin()],
	['app/src/main/res/drawable/ic_launcher_foreground.xml', foreground()],
	['app/src/main/res/values/ic_launcher_background.xml', background()]
]);

async function main(check: boolean): Promise<number> {
	const differ: string[] = [];
	for (const [path, text] of OUTPUTS) {
		const file = join(ANDROID, path);
		if (check) {
			const committed = await readFile(file, 'utf8').catch(() => null);
			if (committed !== text) differ.push(path);
		} else {
			await writeFile(file, text);
		}
	}
	for (const path of differ) process.stderr.write(`mark: apps/android/${path} differs from the mark\n`);
	if (check && differ.length === 0) process.stdout.write(`mark: ${String(OUTPUTS.size)} files match the mark\n`);
	return differ.length === 0 ? 0 : 1;
}

process.exitCode = await main(process.argv.includes('--check'));
